#!/usr/bin/env node
/**
 * Generates src/legal/licenses.gen.ts — the open-source acknowledgements list
 * rendered by the in-app Licenses screen (app/legal/licenses.tsx).
 *
 * What it does:
 *   1. Reads the runtime `dependencies` from package.json (devDependencies are
 *      build-time only and not shipped, so they are excluded).
 *   2. Adds a short list of notable transitive packages that ship in the app
 *      but are not direct dependencies (skipped silently if not installed).
 *   3. Reads each package's node_modules/<pkg>/package.json for its resolved
 *      version and license field, and emits a sorted, committed TypeScript
 *      module.
 *
 * Re-run after changing dependencies:  node tools/gen_licenses.js
 */

'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const OUT_FILE = path.join(ROOT, 'src', 'legal', 'licenses.gen.ts');

/**
 * Notable transitive packages that ship inside the app bundle even though they
 * are not direct dependencies. Any entry not present in node_modules is
 * skipped, so this list is safe across dependency upgrades.
 */
const NOTABLE_TRANSITIVES = [
  '@react-navigation/native',
  '@react-navigation/native-stack',
  'expo-modules-core',
  'expo-asset',
  'expo-font',
  'metro-runtime',
  'react-native-is-edge-to-edge',
];

/** Normalize the various package.json license shapes to a plain string. */
function readLicenseField(pkgJson) {
  const { license, licenses } = pkgJson;
  if (typeof license === 'string' && license.trim() !== '') {
    return license.trim();
  }
  // Legacy object form: { type: "MIT", url: ... }
  if (license && typeof license === 'object' && typeof license.type === 'string') {
    return license.type;
  }
  // Legacy array form: licenses: [{ type: "MIT" }, ...]
  if (Array.isArray(licenses) && licenses.length > 0) {
    const types = licenses
      .map((l) => (l && typeof l.type === 'string' ? l.type : null))
      .filter(Boolean);
    if (types.length > 0) {
      return types.join(' OR ');
    }
  }
  return 'UNKNOWN';
}

/** Read name/version/license for one installed package, or null if absent. */
function readPackage(name) {
  const pkgJsonPath = path.join(ROOT, 'node_modules', ...name.split('/'), 'package.json');
  if (!fs.existsSync(pkgJsonPath)) {
    return null;
  }
  const pkgJson = JSON.parse(fs.readFileSync(pkgJsonPath, 'utf8'));
  return {
    name,
    version: typeof pkgJson.version === 'string' ? pkgJson.version : 'unknown',
    license: readLicenseField(pkgJson),
  };
}

function main() {
  const rootPkg = JSON.parse(
    fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8'),
  );

  const wanted = new Set([
    ...Object.keys(rootPkg.dependencies || {}),
    ...NOTABLE_TRANSITIVES,
  ]);

  const entries = [];
  const missing = [];
  for (const name of wanted) {
    const entry = readPackage(name);
    if (entry === null) {
      missing.push(name);
    } else {
      entries.push(entry);
    }
  }
  entries.sort((a, b) => a.name.localeCompare(b.name));

  const rows = entries
    .map(
      (e) =>
        `  { name: ${JSON.stringify(e.name)}, version: ${JSON.stringify(
          e.version,
        )}, license: ${JSON.stringify(e.license)} },`,
    )
    .join('\n');

  const output = `/**
 * AUTO-GENERATED by tools/gen_licenses.js — do not edit by hand.
 * Regenerate with:  node tools/gen_licenses.js
 *
 * Open-source packages that ship in the Coil app binary (runtime dependencies
 * plus notable transitive packages), with their resolved versions and declared
 * licenses, sorted by name. Rendered by app/legal/licenses.tsx.
 */

export interface LicenseEntry {
  name: string;
  version: string;
  license: string;
}

export const LICENSES: LicenseEntry[] = [
${rows}
];
`;

  fs.writeFileSync(OUT_FILE, output, 'utf8');

  const flagged = entries.filter(
    (e) => e.license === 'UNKNOWN' || /GPL|AGPL|SSPL/i.test(e.license),
  );
  console.log(`Wrote ${entries.length} entries to ${path.relative(ROOT, OUT_FILE)}`);
  if (missing.length > 0) {
    console.log(`Skipped (not installed): ${missing.join(', ')}`);
  }
  if (flagged.length > 0) {
    console.log('Review these licenses:');
    for (const e of flagged) {
      console.log(`  ${e.name}@${e.version}: ${e.license}`);
    }
  }
}

main();
